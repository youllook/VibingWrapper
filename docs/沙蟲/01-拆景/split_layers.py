names = ['layer-near.png','layer-midnear.png','layer-mid.png','layer-far.png']
stats = []
reconstructed = np.zeros((H,W,3),dtype=np.uint8)
count = np.zeros((H,W),dtype=np.uint8)
for idx, name in enumerate(names):
    mask = labels == idx
    out = np.zeros((H,W,4),dtype=np.uint8)
    out[mask,:3] = rgb[mask]
    out[mask,3] = 255
    path = ROOT / name
    Image.fromarray(out).save(path)
    check = np.asarray(Image.open(path))
    assert check.shape == (941,1672,4)
    assert np.array_equal(check[mask,:3], rgb[mask])
    count += check[...,3] > 0
    reconstructed[mask] = check[mask,:3]
    stats.append({'file':name,'bytes':path.stat().st_size,
                  'opaque_pixels':int(mask.sum()),
                  'opaque_percent':float(mask.mean()*100)})
assert np.all(count == 1), 'Every pixel must have exactly one owner'
assert np.array_equal(reconstructed,rgb), 'Reconstruction must be pixel exact'

