# Exclusive allocation is required: partially transparent overlapping mattes
# would violate that constraint. A narrow deterministic coverage dither gives
# dust edges a soft visual transition while retaining exact source pixels.
rng = np.random.default_rng(430)
def coverage(mask, radius):
    probability = np.asarray(Image.fromarray(mask.astype('uint8')*255).filter(
        ImageFilter.GaussianBlur(radius)), dtype=float)/255
    return rng.random((H,W)) < probability

