def poly(points):
    a=np.zeros((H,W),np.uint8)
    cv2.fillPoly(a,[np.array(points,np.int32)],1)
    return a

def refine(a, radius=4):
    # Only a narrow band around the hand-traced silhouette is uncertain.
    ys,xs=np.where(a)
    x0=max(0,xs.min()-radius-3); x1=min(W,xs.max()+radius+4)
    y0=max(0,ys.min()-radius-3); y1=min(H,ys.max()+radius+4)
    m=a[y0:y1,x0:x1]
    k=cv2.getStructuringElement(cv2.MORPH_ELLIPSE,(2*radius+1,2*radius+1))
    inner=cv2.erode(m,k); outer=cv2.dilate(m,k)
    gc=np.full(m.shape,cv2.GC_BGD,np.uint8)
    gc[outer>0]=cv2.GC_PR_BGD; gc[m>0]=cv2.GC_PR_FGD; gc[inner>0]=cv2.GC_FGD
    cv2.grabCut(bgr[y0:y1,x0:x1].copy(),gc,None,np.zeros((1,65)),np.zeros((1,65)),4,cv2.GC_INIT_WITH_MASK)
    out=np.zeros_like(a); out[y0:y1,x0:x1]=np.isin(gc,[cv2.GC_FGD,cv2.GC_PR_FGD])
    return out

def assign(points,n,r=0):
    a=poly(points)
    if r:a=refine(a,r)
    labels[a>0]=n
    return a

